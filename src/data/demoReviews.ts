/**
 * Dynamically computes mathematical statistics from any CustomerReview array.
 * Formula:
 * averageRating = sum(all ratings) / totalReviews, rounded to 1 decimal place.
 * percentage = (count / totalReviews) * 100
 */
export function calculateReviewStats(reviews: CustomerReview[]): ReviewRatingStats {
  const total = reviews.length;
  if (total === 0) {
    return {
      averageRating: 0,
      totalReviews: 0,
      fiveStarsCount: 0,
      fiveStarsPct: 0,
      fourAndHalfCount: 0,
      fourStarsCount: 0,
      fourStarsPct: 0,
      threeAndHalfCount: 0,
      threeStarsCount: 0,
      threeStarsPct: 0,
      twoStarsCount: 0,
      twoStarsPct: 0,
      oneStarCount: 0,
      oneStarPct: 0,
      destinations: []
    };
  }

  const sumRatings = reviews.reduce((acc, r) => acc + r.rating, 0);
  const avg = Math.round((sumRatings / total) * 10) / 10;

  // Star counts
  const fiveStars = reviews.filter(r => r.rating === 5).length;
  const fourAndHalf = reviews.filter(r => r.rating === 4.5).length;
  const fourStars = reviews.filter(r => r.rating === 4).length;
  const threeAndHalf = reviews.filter(r => r.rating === 3.5).length;
  const threeStars = reviews.filter(r => r.rating === 3).length;
  const twoStars = reviews.filter(r => r.rating >= 2 && r.rating < 3).length;
  const oneStar = reviews.filter(r => r.rating < 2).length;

  // Unique destinations extracted dynamically
  const destinationsSet = new Set<string>();
  reviews.forEach(r => {
    if (r.tripDestination) {
      destinationsSet.add(r.tripDestination);
    }
  });

  return {
    averageRating: avg,
    totalReviews: total,
    fiveStarsCount: fiveStars,
    fiveStarsPct: Math.round((fiveStars / total) * 100),
    fourAndHalfCount: fourAndHalf,
    fourStarsCount: fourStars + fourAndHalf,
    fourStarsPct: Math.round(((fourStars + fourAndHalf) / total) * 100),
    threeAndHalfCount: threeAndHalf,
    threeStarsCount: threeStars + threeAndHalf,
    threeStarsPct: Math.round(((threeStars + threeAndHalf) / total) * 100),
    twoStarsCount: twoStars,
    twoStarsPct: Math.round((twoStars / total) * 100),
    oneStarCount: oneStar,
    oneStarPct: Math.round((oneStar / total) * 100),
    destinations: Array.from(destinationsSet).sort()
  };
}
